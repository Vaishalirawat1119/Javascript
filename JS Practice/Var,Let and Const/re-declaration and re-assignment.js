//var
//we can re-declare and re-assign
var a = 1;
var a = 2;

a = 4;
console.log(a);


//let
//we can re-assign but not re-declare
let b = 3;
// let b = 6; //error

b = 8;
console.log(b);


//const
//we cannot re-assign or re-declare
const c = 12;
// const c = 5; //error

// c = 9; //error
console.log(c);

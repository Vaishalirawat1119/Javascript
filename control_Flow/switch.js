//switch-case statement

// syntax:
// switch (key) {
//     case value:
        
//         break;

//     default:
//         break;
// }

// Example:
const month = 6;

switch (month) {
    case 1:
        console.log("january");
        break;
    case 2:
        console.log("february");
        break;
    case 3:
        console.log("march");
        break;
    case 4:
        console.log("april");
        break;
    case 5:
        console.log("may");
        break;

    default:
        console.log("invalid month");
        break;
}